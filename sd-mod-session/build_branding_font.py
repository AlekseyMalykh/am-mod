"""Generate src/branding_font_aa.h: anti-aliased ASCII glyphs for the splash.

DejaVu Sans Mono (Bitstream Vera licence, redistributable) is rasterised at
two pixel sizes into 8-bit coverage masks. The splash blends them over the
logo background, replacing the coarse 8x8 bitmap font."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
R=Path(__file__).resolve().parent
FONT='/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
sizes={'version':13,'url':11}
out=['/* Generated by build_branding_font.py from DejaVu Sans Mono; do not edit. */',
     '#ifndef AM_BRANDING_FONT_AA_H','#define AM_BRANDING_FONT_AA_H','#include <stdint.h>']
for name,px in sizes.items():
    f=ImageFont.truetype(FONT,px);asc,desc=f.getmetrics();h=asc+desc;w=round(f.getlength('M'))
    rows=[]
    for c in range(32,127):
        im=Image.new('L',(w,h),0);ImageDraw.Draw(im).text((0,0),chr(c),font=f,fill=255)
        rows.append(','.join(str(v) for v in (im.get_flattened_data() if hasattr(im,"get_flattened_data") else im.getdata())))
    out.append('#define AM_FONT_%s_W %d'%(name.upper(),w));out.append('#define AM_FONT_%s_H %d'%(name.upper(),h))
    out.append('static const uint8_t am_font_%s[95][%d]={'%(name,w*h))
    out+=['{%s},'%r for r in rows];out.append('};')
out.append('#endif')
(R/'src/branding_font_aa.h').write_text('\n'.join(out)+'\n')
print({n:(round(ImageFont.truetype(FONT,p).getlength('M')),sum(ImageFont.truetype(FONT,p).getmetrics())) for n,p in sizes.items()})
