/* Bake the approved canvas shapes into a compact, monochrome native atlas.
 * SKIA_CANVAS points to an installed skia-canvas module; no runtime dependency. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {Canvas}=require(process.env.SKIA_CANVAS||'skia-canvas');
const folder=__dirname,canvas=new Canvas(320,180),c=canvas.getContext('2d');
const gain={value:0},clamp=(v,a,b)=>Math.max(a,Math.min(b,v));
const sandbox={c,gain,clamp,Math};
vm.createContext(sandbox);vm.runInContext(fs.readFileSync(path.join(folder,'optocat_shapes.js'),'utf8'),sandbox);
const crop={x:96,y:18,w:112,h:140};
const data=[],offsets=[0];
function capture(draw,box=crop){
 c.clearRect(0,0,320,180);c.lineCap='round';c.lineJoin='round';draw();
 const raw=c.getImageData(box.x,box.y,box.w,box.h).data,values=[];
 for(let i=0;i<raw.length;i+=4){
  let hash=i/4+71;hash=Math.imul(hash^(hash>>>16),0x7feb352d);hash=Math.imul(hash^(hash>>>15),0x846ca68b);hash^=hash>>>16;
  const noise=(hash>>>0)/4294967296-.5;
  values.push(raw[i+3]<100?0:1+Math.round(clamp(raw[i]+noise*23,0,255)*14/255));
 }
 for(let i=0;i<values.length;){let n=1;while(n<16&&i+n<values.length&&values[i+n]===values[i])n++;data.push((n-1)*16+values[i]);i+=n;}
 offsets.push(data.length);
 return values;
}
// Frame order: eye size, signal/look height, reach. Every limb keeps its length.
for(let eye=0;eye<4;eye++)for(let look=0;look<7;look++)for(let reach=0;reach<9;reach++){
 gain.value=eye*6;capture(()=>sandbox.awake(154-look*71/6,reach/8,0));
}
const sleep=offsets.length-1;capture(()=>sandbox.sleep(),{x:96,y:70,w:154,h:90});
const bow=offsets.length-1;capture(()=>sandbox.bow(100,0),{x:180,y:90,w:29,h:25});
const header=`/* Generated by graphics/build_optocat.cjs from the approved canvas artwork. */\n`+
 `#define OPTOCAT_SPRITE_W ${crop.w}\n#define OPTOCAT_SPRITE_H ${crop.h}\n#define OPTOCAT_SLEEP ${sleep}\n#define OPTOCAT_BOW ${bow}\n`+
 `static const unsigned optocat_offsets[]={${offsets.join(',')}};\n`+
 `static const unsigned char optocat_atlas[]={\n`+
 Array.from({length:Math.ceil(data.length/40)},(_,i)=>data.slice(i*40,i*40+40).join(',')).join(',\n')+'\n};\n';
fs.writeFileSync(path.join(folder,'../src/optocat_atlas.inc'),header);
const output=path.join(folder,'../build/compressor/art');fs.mkdirSync(output,{recursive:true});
for(const [name,level,reach,eyes,asleep] of [['watch',-36,0,0,false],['swat',-6,1,0,false],['gain',-6,1,18,false],['sleep',-48,0,0,true]]){
 gain.value=eyes;c.clearRect(0,0,320,180);c.fillStyle='#000';c.fillRect(0,0,320,180);
 c.lineCap='round';c.lineJoin='round';
 if(asleep)sandbox.sleep();else{sandbox.awake(154-(level+48)*71/48,reach,0);sandbox.bow(154-(level+48)*71/48,0);}
 fs.writeFileSync(path.join(output,name+'.png'),canvas.toBufferSync('png'));
}
fs.writeFileSync(path.join(output,'atlas.json'),JSON.stringify({frames:offsets.length-1,bytes:data.length,crop,eyes:4,looks:7,reach:9},null,2));
console.log(JSON.stringify({frames:offsets.length-1,bytes:data.length}));
